"""Civilopedia search over the installed game's files, for grounding advice in the game's own explanations.

How the in-game Civilopedia is put together (Base/modules/base-standard/ui/civilopedia/model-civilopedia.js):
  - structure lives in data XML: Base/modules/base-standard/data/civilopedia.xml (sections, page layouts and their
    chapters, search terms), civilopedia-concepts.xml (concept pages), civilopedia-ages.xml (age/victory concept
    pages), age-*/data/civilopedia-<age>.xml (per-age excludes). Gameplay pages (units, buildings, civs, techs, ...)
    are generated by SQL over the gameplay DB: one page per type (UNIT_*, BUILDING_*, NODE_TECH_*, ...).
  - text lives in localization XML (Base/modules/*/text/en_us/Civilopedia*Text.xml, DLC/*/modules/text/**). A chapter's
    paragraphs are found by key pattern: LOC_PEDIA_[<SECTION>_]PAGE_<PAGEID>_CHAPTER_<CHAPTER>_(BODY|PARA_<n>), its title
    by ..._CHAPTER_<CHAPTER>_TITLE (falling back to LOC_PEDIA_PAGE_CHAPTER_<CHAPTER>_TITLE); a SUMMARY chapter on a
    gameplay page is the type's Description (LOC_<TYPE>_DESCRIPTION).

We can't run the gameplay SQL, so pages are rebuilt from the text keys themselves, with sections and titles taken
from the structure XML and from the Name/Description columns of the data XML. The index is cached in
data/cache/pedia_index.json and rebuilt when any source file changes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from xml.etree import ElementTree as ET

from . import rules

CACHE = rules.CACHE.parent / "pedia_index.json"
INDEX_VERSION = 3

KEY = re.compile(r"^LOC_PEDIA_(?:([A-Z]+)_)?PAGE_(?:(\w+?)_)?CHAPTER_(\w+?)_(TITLE|BODY|PARA_(\d+))$")
PAGE_TITLE = re.compile(r"^LOC_PEDIA_(?:([A-Z]+)_)?PAGE_(\w+)_TITLE$")
ROW = re.compile(r"<Row\b([^>]*?)/?>", re.S)
ATTR = re.compile(r'(\w+)="([^"]*)"')
# type prefix -> section, for pages that only exist as LOC_PEDIA_PAGE_<TYPE>_* keys
PREFIX_SECTION = [("NODE_TECH", "TECHNOLOGIES"), ("NODE_CIVIC", "CULTURE"), ("CIVILIZATION_", "CIVILIZATIONS"),
                  ("LEADER_", "LEADERS"), ("UNIT_", "UNITS"), ("WONDER_", "WONDERS"), ("BUILDING_", "BUILDINGS"),
                  ("QUARTER_", "BUILDINGS"), ("IMPROVEMENT_", "IMPROVEMENTS"), ("ROUTE_", "IMPROVEMENTS"),
                  ("GOVERNMENT_", "GOVERNMENT"), ("BELIEF_", "RELIGION"), ("RESOURCE_", "MAP"), ("BIOME_", "MAP"),
                  ("FEATURE_", "MAP"), ("TERRAIN_", "MAP"), ("AGE_", "AGES"), ("AGES_", "AGES"), ("VICTORY_", "AGES")]
CLASS_SECTION = {"WONDER": "WONDERS", "IMPROVEMENT": "IMPROVEMENTS", "BUILDING": "BUILDINGS"}
CHAPTER_ORDER = ["INTRO", "CONTENT", "BASICS", "SUMMARY", "UNIQUE_ABILITY", "DESCRIPTION", "DETAILED"]


class PediaError(ValueError):
    pass


# ---------------------------------------------------------------- markup

def clean(text: str | None, idx: dict[str, str] | None = None, depth: int = 0) -> str:
    """Game markup -> readable text: {LOC_*} expanded, [TIP:..]x[/TIP] -> x, icons dropped, lists as '- ' lines."""
    if not text:
        return ""
    if idx is not None and depth < 3:
        text = re.sub(r"\{(LOC_\w+)\}", lambda m: clean(idx.get(m.group(1), ""), idx, depth + 1), text)
    text = re.sub(r"\[icon:[^\]]*\]", "", text, flags=re.I)
    text = re.sub(r"\[/?TIP(:[^\]]*)?\]", "", text, flags=re.I)
    text = re.sub(r"\[LI\]", "\n- ", text, flags=re.I)
    text = re.sub(r"\[NN\]", "\n\n", text)
    text = re.sub(r"\[N\]", "\n", text)
    text = re.sub(r"\[B?LIST\]", "", text, flags=re.I)
    text = re.sub(r"\[/B?LIST\]", "\n", text, flags=re.I)
    text = re.sub(r"\[/?[A-Za-z_]+(:[^\]]*)?\]", "", text)
    text = rules.TAG.sub("", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


# ---------------------------------------------------------------- sources

def _extra_text_files() -> list[Path]:
    """English text outside en_us/ folders (many DLCs keep it directly in modules/text/), missed by rules.text_index."""
    return sorted(p for p in (rules.GAME / "DLC").glob("*/modules/text/*.xml"))


def _extra_text(files: list[Path]) -> dict[str, str]:
    out: dict[str, str] = {}
    for f in files:
        try:
            root = ET.parse(f).getroot()
        except (ET.ParseError, OSError):
            continue
        for block in root:
            english = block.tag == "EnglishText"
            for row in block:
                tag = row.get("Tag")
                if not tag or not (english or (row.get("Language") or "").lower().startswith("en")):
                    continue
                t = row.find("Text")
                text = t.text if t is not None else row.text
                if text:
                    out[tag] = text.strip()
    return out


def _structure_files() -> list[Path]:
    roots = [rules.GAME / "Base" / "modules", rules.GAME / "DLC"]
    return sorted({p for r in roots for p in r.rglob("data/**/civilopedia*.xml")})


def _signature(files: list[Path]) -> str:
    h = hashlib.sha1(str(INDEX_VERSION).encode())
    for f in files:
        try:
            st = f.stat()
        except OSError:
            continue
        h.update(f"{f}|{st.st_mtime_ns}|{st.st_size}".encode())
    return h.hexdigest()


def _structure(files: list[Path]) -> dict:
    """Sections, static pages, layout chapters, search terms and excludes from the civilopedia*.xml files."""
    s = {"sections": {}, "pages": {}, "layouts": {}, "terms": {}, "excludes": set(), "groups": {}}
    for f in files:
        try:
            root = ET.parse(f).getroot()
        except (ET.ParseError, OSError):
            continue
        for table in root:
            for r in table.findall("Row"):
                a = r.attrib
                match table.tag:
                    case "CivilopediaSections":
                        s["sections"][a["SectionID"]] = {"name": a.get("Name"), "sort": int(a.get("SortIndex", 0))}
                    case "CivilopediaPages":
                        s["pages"][(a["SectionID"], a["PageID"])] = {"layout": a.get("PageLayoutID"), "name": a.get("Name"),
                                                                     "group": a.get("PageGroupID"), "sort": int(a.get("SortIndex", 0))}
                    case "CivilopediaPageLayoutChapters":
                        s["layouts"].setdefault(a["PageLayoutID"], []).append((int(a.get("SortIndex", 0)), a["ChapterID"]))
                    case "CivilopediaPageSearchTerms":
                        s["terms"].setdefault((a["SectionID"], a["PageID"]), []).append(a["Term"])
                    case "CivilopediaPageExcludes":
                        s["excludes"].add((a.get("SectionID"), a.get("PageID")))
                    case "CivilopediaPageGroups":
                        s["groups"][(a["SectionID"], a["PageGroupID"])] = a.get("Name")
    return s


def _types(files: list[Path]) -> dict[str, tuple[str | None, str | None, str | None]]:
    """Gameplay type -> (Name key, Description key, ConstructibleClass), from any data XML row carrying a Name."""
    out: dict = {}
    for f in files:
        try:
            s = f.read_text(errors="replace")
        except OSError:
            continue
        if 'Name="LOC_' not in s:
            continue
        for m in ROW.finditer(s):
            a = dict(ATTR.findall(m.group(1)))
            name = a.get("Name")
            if not (name and name.startswith("LOC_")):
                continue
            t = next((v for k, v in a.items() if k.endswith("Type") and v and not v.startswith("LOC_")), None)
            if t and t not in out:
                out[t] = (name, a.get("Description"), a.get("ConstructibleClass"))
    return out


# ---------------------------------------------------------------- index

def build_index(idx: dict[str, str] | None = None, structure_files: list[Path] | None = None,
                data_files: list[Path] | None = None, keep_keys: bool = False) -> dict:
    """Prose pages from the install (defaults) or from explicit inputs (civilopedia.py passes a fixture's).
    keep_keys adds each chapter's raw text keys, so callers can re-render the markup (links) themselves."""
    if idx is None:
        idx = dict(rules.text_index())
        idx.update(_extra_text(_extra_text_files()))
    st = _structure(_structure_files() if structure_files is None else structure_files)
    types = _types(rules._data_files() if data_files is None else data_files)
    static_by_id: dict[str, list[str]] = {}
    for sec, pid in st["pages"]:
        static_by_id.setdefault(pid, []).append(sec)

    def section_for(pid: str, prefixed: set[str]) -> str:
        cands = [s for s in static_by_id.get(pid, []) if s not in prefixed]
        if cands:
            return cands[0]
        cls = (types.get(pid) or (None, None, None))[2]
        if cls in CLASS_SECTION:
            return CLASS_SECTION[cls]
        return next((s for p, s in PREFIX_SECTION if pid.startswith(p)), "CONCEPTS")

    # pass 1: collect (section-prefix, page id) -> chapter -> {title, paras}
    raw: dict[tuple[str | None, str], dict[str, dict]] = {}
    for k in idx:
        if not k.startswith("LOC_PEDIA"):
            continue
        m = KEY.match(k)
        if not m:
            continue
        sec, pid, ch, part, n = m.groups()
        if pid is None:  # LOC_PEDIA_<SEC>_PAGE_CHAPTER_*: generic chapter titles, or the front page
            if part == "TITLE":
                continue
            pid = "INTRO"
        c = raw.setdefault((sec, pid), {}).setdefault(ch, {"paras": []})
        if part == "TITLE":
            c["title"] = k
        else:
            c["paras"].append((int(n) if n else 0, k))
    prefixed_secs: dict[str, set[str]] = {}
    for sec, pid in raw:
        if sec:
            prefixed_secs.setdefault(pid, set()).add(sec)

    pages = []
    for (sec, pid), chapters in raw.items():
        section = sec or section_for(pid, prefixed_secs.get(pid, set()))
        if (section, pid) in st["excludes"]:
            continue
        static = st["pages"].get((section, pid), {})
        tname, tdesc, _ = types.get(pid) or (None, None, None)
        title_keys = [static.get("name"), f"LOC_PEDIA_{section}_PAGE_{pid}_TITLE", f"LOC_PEDIA_PAGE_{pid}_TITLE", tname, f"LOC_{pid}_NAME"]
        title = next((clean(idx[t], idx) for t in title_keys if t and t in idx), None) or pid.replace("_", " ").title()
        if tdesc and tdesc in idx and "SUMMARY" not in chapters:
            chapters["SUMMARY"] = {"paras": [(0, tdesc)]}
        order = [c for _, c in sorted(st["layouts"].get(static.get("layout") or "", []))]
        rank = lambda c: (order.index(c) if c in order else len(order) + (CHAPTER_ORDER.index(c) if c in CHAPTER_ORDER else
                          99 if c == "HISTORY" else 50), c)
        chs = []
        for ch in sorted(chapters, key=rank):
            c = chapters[ch]
            paras = [clean(idx[k], idx) for _, k in sorted(c["paras"]) if k in idx]
            paras = [p for p in paras if p]
            if not paras:
                continue
            tkeys = [c.get("title"), f"LOC_PEDIA_{section}_PAGE_CHAPTER_{ch}_TITLE", f"LOC_PEDIA_PAGE_CHAPTER_{ch}_TITLE"]
            ctitle = next((clean(idx[t], idx) for t in tkeys if t and t in idx), ch.replace("_", " ").title())
            chs.append({"id": ch, "title": ctitle, "text": "\n\n".join(paras)}
                       | ({"keys": [k for _, k in sorted(c["paras"]) if k in idx]} if keep_keys else {}))
        if not chs:
            continue
        sname = st["sections"].get(section, {}).get("name")
        group = static.get("group")
        pages.append({"key": f"{section}:{pid}", "section": section, "section_name": clean(idx.get(sname), idx) if sname else section.title(),
                      "group": clean(idx.get(st["groups"].get((section, group)) or "", ""), idx) or group, "page_id": pid,
                      "title": title, "type": pid if pid in types else None,
                      # not in the structure XML nor a live gameplay type: text left over from removed pages
                      "listed": bool(static) or pid in types or (section == "CONCEPTS" and pid == "INTRO"),
                      "terms": [clean(idx.get(t, t), idx) for t in st["terms"].get((section, pid), [])], "chapters": chs})
    sections = {s: {"name": clean(idx.get(v["name"]), idx) if v["name"] else s, "sort": v["sort"]} for s, v in st["sections"].items()}
    pages.sort(key=lambda p: (sections.get(p["section"], {}).get("sort", 999), p["title"]))
    return {"pages": pages, "sections": sections}


_LOADED: dict | None = None


def index(rebuild: bool = False) -> dict:
    global _LOADED
    if not rules.GAME.exists():
        raise PediaError(f"Civ VII install not found at {rules.GAME}")
    if _LOADED and not rebuild:
        return _LOADED
    sig = _signature(rules._text_files() + _extra_text_files() + _structure_files())
    if CACHE.exists() and not rebuild:
        try:
            d = json.loads(CACHE.read_text())
            if d.get("signature") == sig:
                _LOADED = d
                return d
        except (OSError, ValueError):
            pass
    d = build_index() | {"signature": sig}
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps(d))
    _LOADED = d
    return d


# ---------------------------------------------------------------- search

def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9 ]+", " ", s.lower()).strip()


def _score(p: dict, q: str, toks: list[str]) -> float:
    title = _norm(p["title"])
    s = 0.0
    if title == q:
        s += 100
    elif q and q in title:
        s += 60 - min(20, len(title) - len(q))
    elif toks and all(t in title.split() for t in toks):
        s += 40
    terms = [_norm(t) for t in p["terms"]]
    if q in terms:
        s += 50
    body = p.get("_body")
    if body is None:
        body = p["_body"] = _norm(" ".join(c["title"] + " " + c["text"] for c in p["chapters"]))
    if q and q in body:
        s += 10 + min(10, body.count(q))
    if toks:
        hits = sum(1 for t in toks if t in body or t in title)
        s += 15 * hits / len(toks) if hits == len(toks) else 3 * hits / len(toks)
    if p["section"] == "CONCEPTS" and s:
        s += 5  # mechanics explanations beat flavour pages on ties
    return s if p["listed"] else s / 2


def _render(p: dict, max_chars: int, chapters: list[str] | None = None) -> dict:
    out, used, cut = [], 0, False
    for c in p["chapters"]:
        if chapters and c["id"] not in chapters and c["title"].lower() not in [x.lower() for x in chapters]:
            continue
        text = c["text"]
        if max_chars and used + len(text) > max_chars:
            text = text[:max(0, max_chars - used)].rsplit(" ", 1)[0] + " ..."
            cut = True
        out.append({"chapter": c["title"], "text": text})
        used += len(text)
        if cut:
            break
    d = {"title": p["title"], "section": p["section_name"], "key": p["key"]}
    if p["group"]:
        d["group"] = p["group"]
    if p["type"]:
        d["type"] = p["type"]
    if not p["listed"]:
        d["note"] = "not listed in the current in-game Civilopedia (removed or renamed content); may be outdated"
    d["chapters"] = out
    if cut:
        d["truncated"] = True
    return d


def search(query: str = "", section: str | None = None, limit: int = 3, max_chars: int = 2500, with_rules: bool = False,
           chapters: list[str] | None = None) -> dict:
    """Best-matching pages with readable chapter text (each capped at max_chars), plus the titles of other matches.
    An exact page key (SECTION:PAGE_ID) or page id returns that page. Empty query lists a section's pages."""
    ix = index()
    pages = ix["pages"]
    if section:
        sec = section.upper()
        names = {k for k, v in ix["sections"].items()  # forgiving: 'governments', 'Wonder', 'general concepts'
                 if k.rstrip("S") == sec.rstrip("S") or _norm(v["name"]).rstrip("s") == _norm(section).rstrip("s")}
        if not names:
            raise PediaError(f"unknown section {section!r}; one of: {', '.join(ix['sections'])}")
        pages = [p for p in pages if p["section"] in names]
    exact = [p for p in pages if query.strip().upper() in (p["key"].upper(), p["page_id"])]
    if exact:
        p = exact[0]
        r = _render(p, max_chars, chapters) | ({"rules": _rules_for(p["type"])} if with_rules and p["type"] else {})
        return {"query": query, "results": [r]}
    q = _norm(query)
    if not q:
        return {"section": section, "pages": [{"title": p["title"], "key": p["key"], "group": p["group"]} for p in pages]}
    toks = [t for t in q.split() if len(t) > 1]
    scored = sorted(((s, p) for p in pages if (s := _score(p, q, toks)) > 0), key=lambda sp: -sp[0])
    if not scored:
        return {"query": query, "results": [], "hint": "no Civilopedia page matched; try game_rules / `civilizer rules` "
                                                     "for the exact in-game name, or a broader word"}
    results = []
    for s, p in scored[:max(1, limit)]:
        r = _render(p, max_chars, chapters) | {"score": round(s, 1)}
        if with_rules and p["type"]:
            r["rules"] = _rules_for(p["type"])
        results.append(r)
    more = [f"{p['title']} ({p['key']})" for _, p in scored[limit:limit + 10]]
    return {"query": query, "results": results} | ({"other_matches": more} if more else {})


def _rules_for(type_id: str, max_refs: int = 15) -> dict:
    idx = rules.text_index()
    return {"description": clean(idx.get(f"LOC_{type_id}_DESCRIPTION"), idx) or None,
            "references": [{"file": f, "xml": x} for f, x in rules.references(type_id, limit=max_refs)]}


# ---------------------------------------------------------------- CLI

def _print(res: dict, as_json: bool) -> None:
    if as_json:
        print(json.dumps(res, indent=1, ensure_ascii=False))
        return
    if "pages" in res:
        for p in res["pages"]:
            print(f"{p['title']:<40} {p['key']}" + (f"  [{p['group']}]" if p.get("group") else ""))
        return
    if not res["results"]:
        print(res.get("hint", "no match"))
        return
    for r in res["results"]:
        print(f"== {r['title']}  ({r['section']}{' / ' + r['group'] if r.get('group') else ''}; {r['key']})")
        for c in r["chapters"]:
            print(f"\n-- {c['chapter']}\n{c['text']}")
        if r.get("rules"):
            print(f"\n-- Rules ({r['type']})")
            if r["rules"]["description"]:
                print(r["rules"]["description"])
            for ref in r["rules"]["references"]:
                print(f"  {ref['file']}: {ref['xml'][:300]}")
        print()
    if res.get("other_matches"):
        print("Also: " + "; ".join(res["other_matches"]))


def main(argv: list[str]) -> int:
    if argv[:1] and argv[0] in ("build", "search", "page", "links", "compare", "filter", "reachable", "info"):
        from . import civilopedia  # indexed Civilopedia (data/civilopedia.db): search, pages, links, compare

        return civilopedia.main(list(argv))
    ap = argparse.ArgumentParser(prog="civilizer pedia", description="Search the game's Civilopedia (from the install files). "
                                 "Subcommands build | search | page | links | compare | filter | reachable | info use the "
                                 "indexed Civilopedia (data/civilopedia.db); see `civilizer pedia search -h`.")
    ap.add_argument("query", nargs="*", help="title, keyword or page key (SECTION:PAGE_ID); empty with --section lists pages. "
                    "`sections`, `rebuild` and `list SECTION` as the first words act like the flags")
    ap.add_argument("--section", "-s", help="limit to a section (CONCEPTS, AGES, UNITS, BUILDINGS, WONDERS, LEADERS, ...)")
    ap.add_argument("--limit", "-n", type=int, default=1, help="pages to show in full (default 1)")
    ap.add_argument("--max-chars", type=int, default=6000, help="text cap per page (0 = no cap)")
    ap.add_argument("--chapter", action="append", help="only these chapters (id or title, e.g. HISTORY)")
    ap.add_argument("--rules", action="store_true", help="also show the data-XML rules for the page's game type")
    ap.add_argument("--sections", action="store_true", help="list sections")
    ap.add_argument("--rebuild", action="store_true", help="rebuild the cached index")
    ap.add_argument("--json", action="store_true")
    # `civilizer pedia` receives argparse.REMAINDER, which can't start with an option: accept words as commands too
    argv = list(argv)
    if argv[:1] == ["sections"]:
        argv[0] = "--sections"
    elif argv[:1] == ["rebuild"]:
        argv[0] = "--rebuild"
    elif argv[:1] == ["list"] and len(argv) > 1:
        argv[:2] = ["--section", argv[1]]
    a = ap.parse_args(argv)
    try:
        ix = index(rebuild=a.rebuild)
        if a.sections:
            for k, v in sorted(ix["sections"].items(), key=lambda kv: kv[1]["sort"]):
                n = sum(p["section"] == k for p in ix["pages"])
                print(f"{k:<14} {v['name']:<22} {n} pages")
            return 0
        if not a.query and not a.section:
            if a.rebuild:
                print(f"indexed {len(ix['pages'])} pages -> {CACHE}")
                return 0
            ap.error("give a query or --section")
        _print(search(" ".join(a.query), a.section, a.limit, a.max_chars, a.rules, a.chapter), a.json)
    except PediaError as e:
        print(f"error: {e}")
        return 1
    return 0
